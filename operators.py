#Aritmetic operators

#Addition : Made with + sign
addition = 6+1
print("This is the addition w/ + :" , addition)

#Subtraction: Made with - sign
subtraction = 5-1
print("This is subtraction w/ -", subtraction)

#Multiplications: Made with asterisk sign * - ctrl 8 
multiplication= 5*5
print("This is multiplication w/ *", multiplication)

#Division: Made with slash /
division = 10 / 5
print("This is division", division)

#Double division aka floor division: Made with double slash // 
#In order to get the whole number of a division, we use double slash //
double_division = 10 // 3
print("This is double division", double_division)   

